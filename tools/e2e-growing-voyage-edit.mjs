import {chromium} from 'playwright';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {createHash,randomUUID} from 'node:crypto';
import {build} from 'esbuild';
import {seedNative,runtimeMetadata} from './island-e2e-helpers.mjs';
const out=process.env.SANSU_VOYAGE_EDIT_OUTPUT;
assert(out, 'Specify a new SANSU_VOYAGE_EDIT_OUTPUT directory');
await fs.mkdir(out, {recursive:false});
const base=process.env.SANSU_VOYAGE_EDIT_URL ?? 'http://127.0.0.1:5307';
const bundle=await build({stdin:{contents:"export {growingDb,sailGrowingIsland} from './src/domain/growingIsland/repository.ts';",resolveDir:process.cwd()},bundle:true,platform:'browser',format:'esm',write:false,logLevel:'silent',define:{'import.meta.env':JSON.stringify({DEV:false,BASE_URL:'/'}),__APP_VERSION__:'"voyage-edit-diagnostic"',__LIFE_REPLAY_VERSION__:'"voyage-edit-diagnostic"'}});
