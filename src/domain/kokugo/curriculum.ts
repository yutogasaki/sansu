export const KOKUGO_STARTER_UNITS: KokugoUnit[] = definitions.flatMap(([track, entries]) => entries.map(([title, band, introduction], index) => ({
    id: `${track}${String(index + 1).padStart(2, '0')}`, track, title, band, introduction,
})));
export const KOKUGO_UNITS = [...KOKUGO_STARTER_UNITS, ...KANJI_UNITS];
export function kokugoUnit(id: string) {
    const unit = KOKUGO_UNITS.find(unit => unit.id === id);
    if (!unit) throw new Error('国語の 内容を えらびなおしてね。');
    return unit;
}

